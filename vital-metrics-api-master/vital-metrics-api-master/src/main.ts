import { NestFactory } from '@nestjs/core';
import { ValidationPipe } from '@nestjs/common';
import { SwaggerModule, DocumentBuilder } from '@nestjs/swagger';
import { AppModule } from './app.module';

async function bootstrap() {
  const app = await NestFactory.create(AppModule);

  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      forbidNonWhitelisted: true,
      transform: true,
    }),
  );

  const config = new DocumentBuilder()
    .setTitle('Vital Metrics API')
    .setDescription(
      'Professional REST API for vital health metrics tracking. Provides endpoints for user registration, authentication, and health data management.',
    )
    .setVersion('1.0.0')
    .addBearerAuth(
      {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'JWT',
        name: 'JWT',
        description: 'Enter JWT access token',
        in: 'header',
      },
      'JWT-auth',
    )
    .addTag('Authentication', 'User authentication and authorization endpoints')
    .addTag('Users', 'User management endpoints')
    .addTag('Notifications', 'Push notification management')
    .addTag('Device Tokens', 'Device registration for push notifications')
    .addTag('Notification Preferences', 'User notification settings')
    .addTag('Admin', 'Admin-only endpoints for user and platform management')
    .build();

  const document = SwaggerModule.createDocument(app, config);
  SwaggerModule.setup('api/docs', app, document, {
    customSiteTitle: 'Vital Metrics API Docs',
    customfavIcon: 'https://nestjs.com/img/logo-small.svg',
    customCss: '.swagger-ui .topbar { display: none }',
  });

  await app.listen(3000);
  console.log(`Application is running on: http://localhost:3000`);
  console.log(
    `Swagger documentation available at: http://localhost:3000/api/docs`,
  );
}
bootstrap();
